"""Generate Tokens.swift from the design tokens.

The tokens are W3C DTCG JSON files exported from the variables of the Figma design:

    Packages/DesignSystem/tokens/primitives.tokens.json
    Packages/DesignSystem/tokens/theme-light.tokens.json
    Packages/DesignSystem/tokens/theme-dark.tokens.json

Usage:

    scripts/tokens.py           write Packages/DesignSystem/Sources/DesignSystem/Tokens.swift
    scripts/tokens.py --check   exit 1 when the committed Tokens.swift differs from the output

The script uses the Python standard library only.
"""

import argparse
import difflib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TOKENS = ROOT / "Packages/DesignSystem/tokens"
OUTPUT = ROOT / "Packages/DesignSystem/Sources/DesignSystem/Tokens.swift"

HEADER = """\
// This Source Code Form is subject to the terms of the Mozilla Public
// License, v. 2.0. If a copy of the MPL was not distributed with this
// file, You can obtain one at https://mozilla.org/MPL/2.0/.

// Generated by scripts/tokens.py from Packages/DesignSystem/tokens/*.tokens.json.
// Do not edit this file. Change the tokens, then run scripts/tokens.py.

import SwiftUI
"""


def flatten(group, prefix=()):
    """Yield (path, token) for every token in a DTCG group, in file order."""
    for key, value in group.items():
        if key.startswith("$"):
            continue
        if "$value" in value:
            yield prefix + (key,), value
        else:
            yield from flatten(value, prefix + (key,))


def identifier(parts):
    """Turn path parts such as ("text", "on-accent") into textOnAccent."""
    words = []
    for part in parts:
        words.extend(w for w in re.split(r"[^A-Za-z0-9]+", part) if w)
    name = words[0].lower() + "".join(w[:1].upper() + w[1:] for w in words[1:])
    if name[0].isdigit():
        name = "_" + name
    return name


def number(value):
    text = repr(float(value))
    return text[:-2] if text.endswith(".0") else text


def color(value):
    hexa = value.lstrip("#")
    if not re.fullmatch(r"[0-9a-fA-F]{6}([0-9a-fA-F]{2})?", hexa):
        raise ValueError(f"unsupported color value {value!r}")
    channels = [int(hexa[i:i + 2], 16) for i in range(0, len(hexa), 2)]
    if len(channels) == 3:
        channels.append(255)
    r, g, b, a = channels
    return f"SwiftUI.Color(.sRGB, red: {r} / 255, green: {g} / 255, blue: {b} / 255, opacity: {a} / 255)"


def swift_value(token):
    kind = token["$type"]
    value = token["$value"]
    if kind == "color":
        return "SwiftUI.Color", color(value)
    if kind in ("dimension", "duration"):
        unit = value["unit"]
        if kind == "duration" and unit != "ms" or kind == "dimension" and unit != "px":
            raise ValueError(f"unsupported unit {unit!r}")
        scale = 1000 if kind == "duration" else 1
        swift_type = "Double" if kind == "duration" else "CGFloat"
        return swift_type, number(value["value"] / scale)
    if kind == "number":
        return "Double", number(value)
    if kind in ("fontFamily", "string"):
        return "String", json.dumps(value, ensure_ascii=True)
    raise ValueError(f"unsupported token type {kind!r}")


def doc(token, kind):
    lines = []
    if kind == "duration":
        lines.append("In seconds.")
    if kind == "dimension":
        lines.append("In points.")
    if "$description" in token:
        lines.append(token["$description"])
    return lines


def load(name):
    with open(TOKENS / f"{name}.tokens.json", encoding="utf-8") as handle:
        return json.load(handle)


def primitives_enum(tokens):
    groups = {}
    for path, token in flatten(tokens):
        groups.setdefault(path[0], []).append((path[1:], token))
    out = ["/// The primitive tokens of the design.", "public enum Primitives {"]
    for group, entries in groups.items():
        out.append(f"    public enum {group[:1].upper() + group[1:]} {{")
        for path, token in entries:
            swift_type, value = swift_value(token)
            for line in doc(token, token["$type"]):
                out.append(f"        /// {line}")
            out.append(f"        public static let {identifier(path)}: {swift_type} = {value}")
        out.append("    }")
        out.append("")
    out[-1] = "}"
    return out


def theme_struct(light, dark):
    light_tokens = list(flatten(light))
    dark_tokens = dict(flatten(dark))
    if [path for path, _ in light_tokens] != list(dark_tokens):
        raise ValueError("the light and dark themes do not name the same tokens in the same order")
    fields = []
    for path, token in light_tokens:
        swift_type, _ = swift_value(token)
        fields.append((path, identifier(path), swift_type, token))
    out = [
        "/// The semantic tokens of one theme. The design has a light and a dark theme.",
        "public struct ThemeTokens: Sendable {",
    ]
    for path, name, swift_type, token in fields:
        for line in doc(token, token["$type"]):
            out.append(f"    /// {line}")
        out.append(f"    public let {name}: {swift_type}")
    for theme, tokens in (("light", dict(light_tokens)), ("dark", dark_tokens)):
        out.append("")
        out.append(f"    public static let {theme} = ThemeTokens(")
        for index, (path, name, _, _) in enumerate(fields):
            _, value = swift_value(tokens[path])
            comma = "," if index < len(fields) - 1 else ""
            out.append(f"        {name}: {value}{comma}")
        out.append("    )")
    out.append("}")
    return out


def generate():
    lines = [HEADER]
    lines.extend(primitives_enum(load("primitives")))
    lines.append("")
    lines.extend(theme_struct(load("theme-light"), load("theme-dark")))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when Tokens.swift is not current")
    args = parser.parse_args()
    output = generate()
    if not args.check:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(output, encoding="utf-8")
        print(f"wrote {OUTPUT.relative_to(ROOT)}")
        return 0
    current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
    if current == output:
        print(f"{OUTPUT.relative_to(ROOT)} is current.")
        return 0
    diff = difflib.unified_diff(
        current.splitlines(keepends=True),
        output.splitlines(keepends=True),
        fromfile=f"{OUTPUT.relative_to(ROOT)} (committed)",
        tofile=f"{OUTPUT.relative_to(ROOT)} (generated)",
    )
    sys.stdout.writelines(diff)
    print(
        f"error: {OUTPUT.relative_to(ROOT)} differs from what scripts/tokens.py generates. "
        "Run scripts/tokens.py and commit the result.",
        file=sys.stderr,
    )
    return 1


if __name__ == "__main__":
    sys.exit(main())
